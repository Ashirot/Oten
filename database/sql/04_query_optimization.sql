-- OPTIMIZATION EXAMPLE 1: High-Volume Sales Order History Filter
-- ============================================================================

-- 1. Original Query:
-- Filters orders by date range and status while joining customer details.
-- In an unindexed or poorly indexed table, MySQL must scan every row (Full Table Scan).

SELECT 
    o.order_number, 
    o.created_at, 
    o.order_status, 
    o.total_amount, 
    u.name AS customer_name
FROM orders o
LEFT JOIN users u ON o.user_id = u.id
WHERE o.created_at >= '2026-01-01' 
  AND o.order_status = 'delivered';

-- 2. Explanation of what the query does:
-- Retrieves all delivered customer orders placed on or after Jan 1, 2026,
-- joining the users table to retrieve the customer's full name for delivery audit reporting.

-- 3. Execution Plan of Original Query (EXPLAIN):
EXPLAIN FORMAT=TREE
SELECT 
    o.order_number, 
    o.created_at, 
    o.order_status, 
    o.total_amount, 
    u.name AS customer_name
FROM orders o
LEFT JOIN users u ON o.user_id = u.id
WHERE o.created_at >= '2026-01-01' 
  AND o.order_status = 'delivered';

-- 4. Optimization Technique Applied:
-- TECHNIQUE: Multi-Column Composite B-Tree Index on (order_status, created_at)
-- REASON: Equality filter (order_status = 'delivered') should precede range filter (created_at >= ...)
-- In InnoDB, a composite index allows MySQL to jump straight to the 'delivered' index bucket
-- and scan only the date range slice, eliminating a table scan.

-- Index Definition:
-- In Laravel migrations, this was created as `orders_order_status_created_at_index`:
-- In raw SQL: CREATE INDEX idx_orders_status_created ON orders (order_status, created_at);

-- 5. Optimized Query (utilizing the composite index):
EXPLAIN FORMAT=TREE
SELECT 
    o.order_number, 
    o.created_at, 
    o.order_status, 
    o.total_amount, 
    u.name AS customer_name
FROM orders o USE INDEX (orders_order_status_created_at_index, idx_orders_status_created)
LEFT JOIN users u ON o.user_id = u.id
WHERE o.order_status = 'delivered'
  AND o.created_at >= '2026-01-01';

-- 6. Results & Plan Comparison:
-- BEFORE OPTIMIZATION:
-- Access Type: ALL (Full Table Scan)
-- Rows Examined: Scans all N rows in the orders table.
-- Filter: (orders.order_status = 'delivered') AND (orders.created_at >= TIMESTAMP'2026-01-01 00:00:00')
--
-- AFTER OPTIMIZATION:
-- Access Type: range / ref using idx_orders_status_created
-- Rows Examined: Restricted strictly to delivered records within the date boundary.
-- Performance Observation: Significantly reduces I/O page reads from buffer pool as table volume grows.


-- ============================================================================
-- OPTIMIZATION EXAMPLE 2: Correlated Scalar Subquery vs Indexed Grouped JOIN
-- ============================================================================

-- 1. Original Query:
-- Calculates product counts and revenue per category using correlated scalar subqueries.

SELECT 
    c.name AS category_name,
    (SELECT COUNT(*) 
     FROM products p 
     WHERE p.category_id = c.id) AS total_products,
    (SELECT COALESCE(SUM(oi.subtotal), 0.00) 
     FROM order_items oi 
     JOIN products p2 ON oi.product_id = p2.id 
     WHERE p2.category_id = c.id) AS category_revenue
FROM categories c;

-- 2. Explanation of what the query does:
-- For every category, evaluates two correlated subqueries to calculate:
-- (a) total menu products belonging to that category,
-- (b) cumulative sales revenue generated by those products.

-- 3. Execution Plan of Original Query:
EXPLAIN FORMAT=TREE
SELECT 
    c.name AS category_name,
    (SELECT COUNT(*) 
     FROM products p 
     WHERE p.category_id = c.id) AS total_products,
    (SELECT COALESCE(SUM(oi.subtotal), 0.00) 
     FROM order_items oi 
     JOIN products p2 ON oi.product_id = p2.id 
     WHERE p2.category_id = c.id) AS category_revenue
FROM categories c;

-- 4. Optimization Technique Applied:
-- TECHNIQUE: Subquery Elimination via Indexed Grouped JOIN
-- REASON: In the original query, MySQL executes the subqueries N times (where N is the number of categories).
-- This O(N) sub-execution pattern causes repeated index lookups and join scans.
-- By converting this into a single LEFT JOIN with products and order_items grouped by category ID,
-- MySQL executes a single linear pass using the existing Foreign Key indexes.

-- 5. Optimized Query:
EXPLAIN FORMAT=TREE
SELECT 
    c.name AS category_name,
    COUNT(DISTINCT p.id) AS total_products,
    COALESCE(SUM(oi.subtotal), 0.00) AS category_revenue
FROM categories c
LEFT JOIN products p ON c.id = p.category_id
LEFT JOIN order_items oi ON p.id = oi.product_id
GROUP BY c.id, c.name;

-- 6. Results & Plan Comparison:
-- BEFORE OPTIMIZATION:
-- Plan Type: DEPENDENT SUBQUERY executed for each outer row.
-- Cost: High CPU overhead due to repeated subquery context switches.
--
-- AFTER OPTIMIZATION:
-- Plan Type: Single join pass utilizing primary and foreign key indexes (eq_ref and ref).
-- Cost: Reduced CPU cycle count and memory overhead. Temporary table creation for subqueries is completely eliminated.
